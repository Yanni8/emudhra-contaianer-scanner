// isDefaultSystemStore reports whether p is the system bundle (as the
// catalogue classifies it) or a default OpenSSL certificate directory, i.e.
// the store OpenSSL-based programs would use without any variable set.
func isDefaultSystemStore(p string) bool {
	np := normalisePath(p)
	if defaultCertDirs[strings.ToLower(np)] {
		return true
	}
	return classify(np, nil).Class == ClassSystemBundle
}

// clone returns a copy that shares no slice with the catalogue.
func (s Store) clone() Store {
	s.Consumers = append([]string(nil), s.Consumers...)
	return s
}

// normalisePath turns "./x", "x" and "/x" into the absolute, cleaned "/x".
func normalisePath(p string) string {
	return path.Clean("/" + strings.TrimSpace(p))
}

// splitSegments splits an absolute path into its components; "/" yields nil.
func splitSegments(p string) []string {
	p = strings.Trim(p, "/")
	if p == "" {
		return nil
	}
	return strings.Split(p, "/")
}

// matchSegments matches compiled pattern segments against path segments.
// "**" matches zero or more segments; every other pattern segment matches
// exactly one path segment. The whole path must be consumed.
func matchSegments(pat []segment, segs []string) bool {
	for len(pat) > 0 {
		if pat[0].kind == segAny {
			rest := pat[1:]
			if len(rest) == 0 {
				return true
			}
			// Whatever "**" swallows, the fixed tail after the last "**" has
			// to match the end of the path; check that before backtracking.
			last := lastAny(rest)
			tail := rest[last+1:]
			if len(segs) < len(tail) || !matchFixed(tail, segs[len(segs)-len(tail):]) {
				return false
			}
			if last < 0 {
				return true
			}
			for i := 0; i+len(tail) <= len(segs); i++ {
				if matchSegments(rest, segs[i:]) {
					return true
				}
			}
			return false
		}
		if len(segs) == 0 || !pat[0].match(segs[0]) {
			return false
		}
		pat, segs = pat[1:], segs[1:]
	}
	return len(segs) == 0
}

// matchFixed matches equal-length segment lists without "**".
func matchFixed(pat []segment, segs []string) bool {
	for i := range pat {
		if !pat[i].match(segs[i]) {
			return false
		}
	}
	return true
}

// lastAny returns the index of the last "**" in pat, or -1.
func lastAny(pat []segment) int {
	for i := len(pat) - 1; i >= 0; i-- {
		if pat[i].kind == segAny {
			return i
		}
	}
	return -1
}

// matchGlob matches one pattern against one path (both in any of the forms
// Classify accepts); it is a convenience for tests.
func matchGlob(pattern, p string) bool {
	return matchSegments(compilePattern(pattern), splitSegments(strings.ToLower(normalisePath(p))))
}
