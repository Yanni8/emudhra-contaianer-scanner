// rule maps one glob pattern to a store template. Patterns are matched
// against the cleaned, lower-cased absolute path; "**" matches any number of
// directories and the other segments use path.Match syntax.
type rule struct {
	pattern string
	segs    []segment
	store   Store
}

// segment is one compiled pattern component. The common shapes are matched
// with plain string operations; only irregular globs fall back to path.Match.
type segment struct {
	text string // the original pattern component
	kind segKind
	lit  string // literal core for segPrefix, segSuffix and segContains
	// prefix and suffix are literal fragments a segGlob name must carry; they
	// filter out most names before the backtracking path.Match runs.
	prefix, suffix string
}

type segKind uint8

const (
	segLiteral  segKind = iota // "cacert.pem": name == text
	segAny                     // "**": zero or more path components
	segPrefix                  // "aws-sdk-core-*"
	segSuffix                  // "*.jks"
	segContains                // "*conda*"
	segGlob                    // anything else, via path.Match
)

const globMeta = `*?[\`

func compileRules(rules []rule) []rule {
	for i := range rules {
		rules[i].segs = compilePattern(rules[i].pattern)
	}
	return rules
}

func compilePattern(pattern string) []segment {
	parts := splitSegments(strings.ToLower(pattern))
	segs := make([]segment, len(parts))
	for i, p := range parts {
		segs[i] = compileSegment(p)
	}
	return segs
}

func compileSegment(p string) segment {
	s := segment{text: p}
	if p == "**" {
		s.kind = segAny
		return s
	}
	meta := strings.IndexAny(p, globMeta)
	if meta < 0 {
		s.kind = segLiteral
		return s
	}
	core := strings.Trim(p, "*")
	if !strings.ContainsAny(core, globMeta) {
		// Only leading and/or trailing stars around a literal.
		s.lit = core
		switch {
		case strings.HasPrefix(p, "*") && strings.HasSuffix(p, "*"):
			s.kind = segContains
		case strings.HasPrefix(p, "*"):
			s.kind = segSuffix
		default:
			s.kind = segPrefix
		}
		return s
	}
	s.kind = segGlob
	s.prefix = p[:meta]
	if last := strings.LastIndexAny(p, globMeta); last >= 0 && p[last] == '*' {
		s.suffix = p[last+1:]
	}
	return s
}

func (s segment) match(name string) bool {
	switch s.kind {
	case segLiteral:
		return s.text == name
	case segPrefix:
		return strings.HasPrefix(name, s.lit)
	case segSuffix:
		return strings.HasSuffix(name, s.lit)
	case segContains:
		return strings.Contains(name, s.lit)
	case segAny:
		return true
	}
	if !strings.HasPrefix(name, s.prefix) || !strings.HasSuffix(name, s.suffix) {
		return false
	}
	ok, err := path.Match(s.text, name)
	return err == nil && ok
}

func mkStore(class Class, name, ecosystem string, consumers []string, trusted bool, remediation string) Store {
	return Store{Class: class, Name: name, Ecosystem: ecosystem, Consumers: consumers, TrustedByDefault: trusted, Remediation: remediation}
}

func bundle(name string, consumers []string, rem string) Store {
	return mkStore(ClassSystemBundle, name, ecoSystem, consumers, true, rem)
}

// generated marks a store as regenerated by the distribution's trust tooling.
func generated(s Store) Store {
	s.SystemGenerated = true
	return s
}

// limited marks a store as trusted for one purpose only.
func limited(s Store, purpose string) Store {
	s.LimitedTo = purpose
	return s
}

// javaGenerated is a Java cacerts keystore that the distribution regenerates
// from its system trust store; it carries no Java fix.
func javaGenerated(name, rem string) Store {
	return generated(mkStore(ClassJavaKeystore, name, ecoJava, consumersJavaGenerated, true, rem))
}

func anchorDir(name string, consumers []string, rem string) Store {
	return mkStore(ClassSystemAnchorDir, name, ecoSystem, consumers, true, rem)
}

func sourceDir(name string, consumers []string, rem string) Store {
	return mkStore(ClassSystemSource, name, ecoSystem, consumers, false, rem)
}

func blocklistDir(name string) Store {
	return mkStore(ClassSystemBlocklist, name, ecoSystem, []string{"trust tooling (update-ca-trust, certctl): the certificate is rejected"}, false, remBlocklist)
}

func appBundle(name, ecosystem string, consumers []string, rem string) Store {
	return mkStore(ClassAppBundle, name, ecosystem, consumers, true, rem)
}

