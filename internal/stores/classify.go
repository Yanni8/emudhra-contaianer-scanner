// classify implements Classify.
func classify(p string, header []byte) Store {
	lp := strings.ToLower(normalisePath(p))
	segs := splitSegments(lp)
	for i := range catalogue {
		if matchSegments(catalogue[i].segs, segs) {
			return catalogue[i].store.clone()
		}
	}
	base := path.Base(lp)
	rt, known := runtimeInfo(base)
	executable := isExecutableHeader(header) || isLibraryName(base)
	switch {
	case known && (executable || len(header) == 0):
		// A known runtime name with no header to contradict it is given the
		// benefit of the doubt; a text wrapper script named "node" is not.
		return runtimeStore(rt)
	case executable:
		return mkStore(ClassEmbeddedBinary, "Executable or shared library with embedded certificate data", ecoOther,
			[]string{"the program itself (if it uses the embedded certificates as trust anchors)"}, false, remEmbeddedBin)
	}
	return mkStore(ClassLooseFile, "Certificate file outside any known trust store", ecoOther, consumersUnknown, false, remLoose)
}

// isBlocklistPath implements IsBlocklistPath.
func isBlocklistPath(p string) bool {
	segs := splitSegments(strings.ToLower(normalisePath(p)))
	for i := range blocklistRules {
		if matchSegments(blocklistRules[i].segs, segs) {
			return true
		}
	}
	return false
}

