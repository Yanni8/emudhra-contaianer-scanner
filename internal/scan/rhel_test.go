// p11Object renders one p11-kit certificate object with the given trust
// attribute line ("trusted: true", "x-distrusted: true", ...).
func p11Object(label string, c *x509.Certificate, trustLine string) string {
	var sb strings.Builder
	fmt.Fprintf(&sb, "[p11-kit-object-v1]\nlabel: %q\nclass: certificate\ncertificate-type: x-509\nmodifiable: false\n%s\nnss-mozilla-ca-policy: true\n", label, trustLine)
	sb.Write(pemOf(c))
	sb.WriteString("\n")
	return sb.String()
}

// p11EKUObject renders an x-certificate-extension object that limits the
// certificate's purposes, keyed by its public key as p11-kit does.
func p11EKUObject(t *testing.T, label string, c *x509.Certificate, oids ...asn1.ObjectIdentifier) string {
	t.Helper()
	list, err := asn1.Marshal(oids)
	if err != nil {
		t.Fatal(err)
	}
	ext, err := asn1.Marshal(struct {
		ID       asn1.ObjectIdentifier
		Critical bool
		Value    []byte
	}{asn1.ObjectIdentifier{2, 5, 29, 37}, true, list})
	if err != nil {
		t.Fatal(err)
	}
	var value strings.Builder
	for _, b := range ext {
		fmt.Fprintf(&value, "%%%02x", b)
	}
	var sb strings.Builder
	fmt.Fprintf(&sb, "[p11-kit-object-v1]\nlabel: %q\nclass: x-certificate-extension\nobject-id: 2.5.29.37\nvalue: \"%s\"\nmodifiable: false\n", label, value.String())
	sb.Write(pem.EncodeToMemory(&pem.Block{Type: "PUBLIC KEY", Bytes: c.RawSubjectPublicKeyInfo}))
	sb.WriteString("\n")
	return sb.String()
}

const amznRelease = "NAME=\"Amazon Linux\"\nVERSION=\"2023\"\nID=\"amzn\"\nID_LIKE=\"fedora\"\nVERSION_ID=\"2023\"\nPRETTY_NAME=\"Amazon Linux 2023.9.20261015\"\n"

// buildP11KitFixture builds an Amazon Linux 2023 style tree: a p11-kit
// package source with trust attributes and an EKU-limited anchor, a
// blocklist directory (one file, one link from the anchors directory), the
// extracted bundles still carrying a blocklisted certificate, the generated
// Java cacerts, the hashed directory behind the /etc/ssl/certs symlink and
// an rpm database.
func buildP11KitFixture(t *testing.T) []byte {
	t.Helper()
	g3 := blocklistCert(t, "emsign-ecc-root-ca-g3")
	aaa := blocklistCert(t, "aaa-certificate-services")
	tlsG3 := blocklistCert(t, "emsign-root-tls-ca-g3")
	g1 := blocklistCert(t, "emsign-root-ca-g1")
	c1 := blocklistCert(t, "emsign-root-ca-c1")
	g2 := blocklistCert(t, "emsign-root-ca-g2")
	root := newRoot(t, pkixName("Example Root CA"))
	rpmDB, err := os.ReadFile("../rpmdb/testdata/packages-small.sqlite")
	if err != nil {
		t.Fatal(err)
	}

	b := newTar()
	var source strings.Builder
	source.WriteString("# This file is generated by update-ca-trust.\n\n")
	source.WriteString(p11Object("emSign ECC Root CA - G3", g3, "trusted: true"))
	source.WriteString(p11Object("Comodo AAA Services root", aaa, "trusted: true"))
	source.WriteString(p11EKUObject(t, "Comodo AAA Services root", aaa, oidEmailProtect, oidCodeSigning))
	source.WriteString(p11Object("emSign Root TLS CA - G3", tlsG3, "trusted: true"))
	source.WriteString(p11Object("emSign Root CA - G1", g1, "trusted: true"))
	source.WriteString(p11Object("Explicitly Distrust emSign Root CA - C1", c1, "x-distrusted: true"))
	source.WriteString(p11Object("emSign Root CA - G2", g2, "trusted: false"))
	source.WriteString(p11Object("Example Root CA", root, "trusted: true"))
	b.file("usr/share/pki/ca-trust-source/ca-bundle.trust.p11-kit", []byte(source.String()))

	b.file("etc/pki/ca-trust/source/blocklist/emsign-root-tls-ca-g3.pem", pemOf(tlsG3))
	b.file("etc/pki/ca-trust/source/anchors/legacy-g1.pem", pemOf(g1))
	b.symlink("etc/pki/ca-trust/source/blocklist/legacy-g1.pem", "../anchors/legacy-g1.pem")
	b.file("etc/pki/ca-trust/source/anchors/c1.pem", pemOf(c1))

	tlsBundle := append(append(append([]byte(nil), pemOf(root)...), pemOf(g3)...), pemOf(tlsG3)...)
	b.file("etc/pki/ca-trust/extracted/pem/tls-ca-bundle.pem", tlsBundle)
	b.file("etc/pki/ca-trust/extracted/pem/email-ca-bundle.pem", pemOf(aaa))
	b.file("etc/pki/ca-trust/extracted/pem/objsign-ca-bundle.pem", pemOf(aaa))
	trustBundle := trustedPEM(t, aaa, certAux{Trust: []asn1.ObjectIdentifier{oidCodeSigning, oidEmailProtect}, Alias: "Comodo AAA Services root"})
	trustBundle = append(trustBundle, trustedPEM(t, g3, certAux{Trust: []asn1.ObjectIdentifier{oidServerAuth, oidClientAuth}, Alias: "emSign ECC Root CA - G3"})...)
	trustBundle = append(trustBundle, trustedPEM(t, tlsG3, certAux{Reject: []asn1.ObjectIdentifier{oidServerAuth, oidClientAuth, oidCodeSigning, oidEmailProtect}, Alias: "emSign Root TLS CA - G3"})...)
	b.file("etc/pki/ca-trust/extracted/openssl/ca-bundle.trust.crt", trustBundle)
	b.file("etc/pki/ca-trust/extracted/pem/directory-hash/emSign_ECC_Root_CA_-_G3.pem", pemOf(g3))
	b.symlink("etc/pki/ca-trust/extracted/pem/directory-hash/14bc7599.0", "emSign_ECC_Root_CA_-_G3.pem")
	b.symlink("etc/pki/ca-trust/extracted/pem/directory-hash/ca-bundle.crt", "../tls-ca-bundle.pem")
	b.file("etc/pki/ca-trust/extracted/java/cacerts", writeJKS(map[string]*x509.Certificate{"emsigneccrootca-g3": g3, "emsignroottlsca-g3": tlsG3}, []string{"emsigneccrootca-g3", "emsignroottlsca-g3"}))
	b.symlink("etc/pki/java/cacerts", "/etc/pki/ca-trust/extracted/java/cacerts")
	b.symlink("etc/ssl/certs", "/etc/pki/ca-trust/extracted/pem/directory-hash")
	b.symlink("etc/pki/tls/certs/ca-bundle.crt", "/etc/pki/ca-trust/extracted/pem/tls-ca-bundle.pem")

	b.file("etc/os-release", []byte(amznRelease))
	b.file("var/lib/rpm/rpmdb.sqlite", rpmDB)
	b.file("usr/bin/rpm", append([]byte(nil), elfHeader...))
	b.file("usr/bin/microdnf", append([]byte(nil), elfHeader...))
	return b.bytes()
}

var oidClientAuth = asn1.ObjectIdentifier{1, 3, 6, 1, 5, 5, 7, 3, 2}

func TestP11KitTrustTree(t *testing.T) {
	res := scanTar(t, buildP11KitFixture(t), Options{Env: []string{"SSL_CERT_FILE=/etc/ssl/certs/ca-bundle.crt", "SSL_CERT_DIR=/etc/ssl/certs"}})

	const (
		source    = "/usr/share/pki/ca-trust-source/ca-bundle.trust.p11-kit"
		tlsBundle = "/etc/pki/ca-trust/extracted/pem/tls-ca-bundle.pem"
		openssl   = "/etc/pki/ca-trust/extracted/openssl/ca-bundle.trust.crt"
		hashDir   = "/etc/pki/ca-trust/extracted/pem/directory-hash/emSign_ECC_Root_CA_-_G3.pem"
		cacerts   = "/etc/pki/ca-trust/extracted/java/cacerts"
	)
	type want struct {
		path, entry string
		severity    blocklist.Severity
		trust       string
		purposes    []string
		detail      string // substring
	}
	wants := []want{
		{source, "emsign-ecc-root-ca-g3", blocklist.SeverityHigh, TrustTrusted, []string{"serverAuth", "clientAuth", "codeSigning", "emailProtection"}, "marked as a trust anchor by the store itself (trusted: true)"},
		{source, "aaa-certificate-services", blocklist.SeverityMedium, TrustTrusted, []string{"codeSigning", "emailProtection"}, "not for TLS server authentication"},
		{source, "emsign-root-tls-ca-g3", blocklist.SeverityInfo, TrustDistrusted, nil, "blocklisted by /etc/pki/ca-trust/source/blocklist/emsign-root-tls-ca-g3.pem: p11-kit gives the blocklist precedence"},
		{source, "emsign-root-ca-g1", blocklist.SeverityInfo, TrustDistrusted, nil, "blocklisted by /etc/pki/ca-trust/source/blocklist/legacy-g1.pem"},
		{source, "emsign-root-ca-c1", blocklist.SeverityInfo, TrustDistrusted, nil, "marked distrusted by the store itself (x-distrusted: true)"},
		{source, "emsign-root-ca-g2", blocklist.SeverityInfo, TrustUnknown, nil, "source file without anchor flags (trusted: false)"},
		{"/etc/pki/ca-trust/source/blocklist/emsign-root-tls-ca-g3.pem", "emsign-root-tls-ca-g3", blocklist.SeverityInfo, TrustDistrusted, nil, "stored in a blocklist directory"},
		{"/etc/pki/ca-trust/source/anchors/legacy-g1.pem", "emsign-root-ca-g1", blocklist.SeverityInfo, TrustDistrusted, nil, "linked from a blocklist directory as /etc/pki/ca-trust/source/blocklist/legacy-g1.pem"},
		{"/etc/pki/ca-trust/source/anchors/c1.pem", "emsign-root-ca-c1", blocklist.SeverityInfo, TrustDistrusted, nil, "blocklisted by " + source},
		{tlsBundle, "emsign-ecc-root-ca-g3", blocklist.SeverityHigh, TrustTrusted, nil, "explicitly selected by SSL_CERT_FILE=/etc/ssl/certs/ca-bundle.crt"},
		{tlsBundle, "emsign-root-tls-ca-g3", blocklist.SeverityHigh, TrustTrusted, nil, "stale: run update-ca-trust"},
		{"/etc/pki/ca-trust/extracted/pem/email-ca-bundle.pem", "aaa-certificate-services", blocklist.SeverityLow, TrustTrusted, []string{"emailProtection"}, "trusted for emailProtection only: no exposure"},
		{"/etc/pki/ca-trust/extracted/pem/objsign-ca-bundle.pem", "aaa-certificate-services", blocklist.SeverityMedium, TrustTrusted, []string{"codeSigning"}, "trusted for codeSigning only, not for TLS server authentication"},
		{openssl, "aaa-certificate-services", blocklist.SeverityMedium, TrustTrusted, []string{"codeSigning", "emailProtection"}, "store flags: trust: codeSigning, emailProtection"},
		{openssl, "emsign-ecc-root-ca-g3", blocklist.SeverityHigh, TrustTrusted, []string{"serverAuth", "clientAuth"}, "store flags"},
		{openssl, "emsign-root-tls-ca-g3", blocklist.SeverityInfo, TrustDistrusted, nil, "marked distrusted by the store itself"},
		{hashDir, "emsign-ecc-root-ca-g3", blocklist.SeverityHigh, TrustTrusted, nil, "explicitly selected by SSL_CERT_DIR=/etc/ssl/certs"},
		{cacerts, "emsign-ecc-root-ca-g3", blocklist.SeverityHigh, TrustTrusted, nil, "trusted without further configuration"},
		{cacerts, "emsign-root-tls-ca-g3", blocklist.SeverityHigh, TrustTrusted, nil, "stale: run update-ca-trust"},
	}
	for _, w := range wants {
		f, ok := findingFor(res, w.path, w.entry)
		if !ok {
			t.Errorf("missing finding %s in %s", w.entry, w.path)
			continue
		}
		if f.Severity != w.severity || f.Trust.State != w.trust || !equalStrings(f.Trust.Purposes, w.purposes) || !strings.Contains(f.Trust.Detail, w.detail) {
			t.Errorf("%s in %s: severity %s trust %+v; want %s %s %v containing %q", w.entry, w.path, f.Severity, f.Trust, w.severity, w.trust, w.purposes, w.detail)
		}
	}
	if n := len(res.Findings); n != len(wants) {
		var got []string
		for _, f := range res.Findings {
			got = append(got, fmt.Sprintf("%s:%s(%s %s)", f.Path, f.EntryID, f.Severity, f.Trust.State))
		}
		t.Errorf("got %d findings, want %d:\n%s", n, len(wants), strings.Join(got, "\n"))
	}
	wantCounts := map[string]int{"critical": 0, "high": 7, "medium": 3, "low": 1, "info": 8}
	for k, v := range wantCounts {
		if res.Summary.FindingsBySeverity[k] != v {
			t.Errorf("count %s = %d, want %d", k, res.Summary.FindingsBySeverity[k], v)
		}
	}

	// Remediation: generated stores get the distribution's action, never the JDK fix.
	if f, _ := findingFor(res, cacerts, "emsign-ecc-root-ca-g3"); strings.Contains(f.Remediation, "Java/OpenJDK") || strings.Contains(f.Remediation, "Upgrade the JDK") || !strings.Contains(f.Remediation, "Amazon Linux") || !strings.Contains(f.Remediation, "/etc/pki/ca-trust/source/blocklist/") || !strings.Contains(f.Store.Name, "generated from the system trust store") {
		t.Errorf("generated cacerts remediation = %q (store %q)", f.Remediation, f.Store.Name)
	}
	if f, _ := findingFor(res, cacerts, "emsign-root-tls-ca-g3"); !strings.HasPrefix(f.Remediation, "Run update-ca-trust so that the generated stores drop the blocklisted certificate") {
		t.Errorf("stale cacerts remediation = %q", f.Remediation)
	}
	if f, _ := findingFor(res, source, "emsign-ecc-root-ca-g3"); !strings.Contains(f.Remediation, "p11-kit trust source") || !strings.Contains(f.Remediation, "Amazon Linux") {
		t.Errorf("source remediation = %q", f.Remediation)
	}
	if f, _ := findingFor(res, source, "emsign-root-tls-ca-g3"); !strings.Contains(f.Remediation, "No action needed") {
		t.Errorf("blocklisted source remediation = %q", f.Remediation)
	}
	if f, _ := findingFor(res, "/etc/pki/ca-trust/source/anchors/legacy-g1.pem", "emsign-root-ca-g1"); f.Store.Class != stores.ClassSystemBlocklist || !strings.Contains(f.Trust.Detail, "identified by the link name /etc/pki/ca-trust/source/blocklist/legacy-g1.pem") {
		t.Errorf("anchor linked from the blocklist: store %s detail %q", f.Store.Class, f.Trust.Detail)
	}

	// Aliases through the /etc/ssl/certs directory symlink.
	if f, _ := findingFor(res, hashDir, "emsign-ecc-root-ca-g3"); !equalStrings(f.Aliases, []string{"/etc/pki/ca-trust/extracted/pem/directory-hash/14bc7599.0", "/etc/ssl/certs/14bc7599.0", "/etc/ssl/certs/emSign_ECC_Root_CA_-_G3.pem"}) {
		t.Errorf("hashed directory aliases = %v", f.Aliases)
	}
	if f, _ := findingFor(res, tlsBundle, "emsign-ecc-root-ca-g3"); !equalStrings(f.Aliases, []string{"/etc/pki/ca-trust/extracted/pem/directory-hash/ca-bundle.crt", "/etc/pki/tls/certs/ca-bundle.crt", "/etc/ssl/certs/ca-bundle.crt"}) {
		t.Errorf("tls bundle aliases = %v", f.Aliases)
	}
	if f, _ := findingFor(res, cacerts, "emsign-ecc-root-ca-g3"); !equalStrings(f.Aliases, []string{"/etc/pki/java/cacerts"}) || strings.Contains(f.Trust.Detail, "SSL_CERT_DIR") {
		t.Errorf("cacerts aliases %v detail %q", f.Aliases, f.Trust.Detail)
	}

	// Packages from the rpm database.
	pkgs := packagesByKey(res)
	if p := pkgs["rpm:ca-certificates"]; p.Version != "2025.2.80_v9.0.305-91.el9" || p.Outdated != nil || p.FixedVersion != "" || !strings.Contains(p.Note, "no fixed version known") || p.Reference != "https://alas.aws.amazon.com/" {
		t.Errorf("rpm ca-certificates = %+v", p)
	}
	if p := pkgs["rpm:openssl-libs"]; p.Version != "1:3.5.8-2.el9_8" || p.Outdated != nil {
		t.Errorf("rpm openssl-libs = %+v", p)
	}
	if p := pkgs["rpm:p11-kit"]; p.Version != "0.26.4-1.el9_8" {
		t.Errorf("rpm p11-kit = %+v", p)
	}
	for _, name := range []string{"rpm:gpg-pubkey", "rpm:zlib", "rpm:big-package"} {
		if _, ok := pkgs[name]; ok {
			t.Errorf("%s must not be listed", name)
		}
	}
	if res.Summary.PackageDatabase != "rpm (sqlite)" || !res.Summary.SystemBundleFound || res.OS.ID != "amzn" {
		t.Errorf("summary = %+v os = %+v", res.Summary, res.OS)
	}
	if len(res.Warnings) != 0 {
		t.Errorf("warnings = %v", res.Warnings)
	}
	for _, f := range res.Findings {
		if f.Certificate.Kind == certs.KindSPKI {
			t.Errorf("bare key reported for %s in %s: the p11-kit extension object's key must be folded into the certificate", f.EntryID, f.Path)
		}
	}
}

func TestRPMDatabaseNotParsed(t *testing.T) {
	b := newTar()
	b.file("etc/os-release", []byte("ID=rhel\nVERSION_ID=\"8.10\"\nID_LIKE=\"fedora\"\nPRETTY_NAME=\"Red Hat Enterprise Linux 8.10\"\n"))
	b.file("var/lib/rpm/Packages", randomBytes(11, 4096))
	b.file("etc/pki/ca-trust/extracted/pem/tls-ca-bundle.pem", pemOf(blocklistCert(t, "emsign-ecc-root-ca-g3")))
	b.file("usr/bin/yum", append([]byte(nil), elfHeader...))
	res := scanTar(t, b.bytes(), Options{})
	if !strings.HasPrefix(res.Summary.PackageDatabase, "rpm (bdb, not parsed: ") || len(res.Packages) != 0 {
		t.Errorf("package database = %q packages = %+v", res.Summary.PackageDatabase, res.Packages)
	}
	if len(res.Warnings) != 1 || !strings.Contains(res.Warnings[0], "/var/lib/rpm/Packages: rpm database not read") {
		t.Errorf("warnings = %v", res.Warnings)
	}
	f, ok := findingFor(res, "/etc/pki/ca-trust/extracted/pem/tls-ca-bundle.pem", "emsign-ecc-root-ca-g3")
	if !ok || !strings.Contains(f.Remediation, "Red Hat Enterprise Linux") || !strings.Contains(f.Remediation, "RHSB-2026-012") || strings.Contains(f.Remediation, "Distrust this CA") {
		t.Errorf("RHEL remediation = %q (ok %v)", f.Remediation, ok)
	}
}
